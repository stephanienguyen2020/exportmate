import { test, expect } from "@playwright/test";

test("real FastAPI/Postgres round trip: onboarding, import, persistence and playbook", async ({ page }) => {
  test.skip(process.env.TEST_REAL_BACKEND !== "1", "Run with TEST_REAL_BACKEND=1 and the local backend on :8000.");
  const email = `frontend-test-${Date.now()}@example.com`;
  await page.goto("/#/login");
  await page.getByLabel("Email", { exact: true }).fill(email);
  await page.getByLabel("Password", { exact: true }).fill("local-test-password");
  await page.getByRole("button", { name: "Sign in", exact: true }).click();
  await expect(page).toHaveURL(/onboarding/);
  await page.getByLabel("Company name").fill("Frontend integration test");
  await page.getByRole("button", { name: "Continue", exact: true }).click();
  await page.getByRole("button", { name: "Continue", exact: true }).click();
  await page.getByRole("button", { name: "Open workspace" }).click();
  await expect(page).toHaveURL(/workspace\/data/);
  await page.locator('input[type="file"]').setInputFiles({ name: "frontend-check.csv", mimeType: "text/csv", buffer: Buffer.from("id,product,supplier,destination,value,shipDate,hsCode\nFRONTEND-CHECK,Test panels,Test supplier,EU,1234.56,2027-01-21,0401.10\n") });
  await expect(page.getByRole("button", { name: "Import 1 orders" })).toBeEnabled();
  await page.getByRole("button", { name: "Import 1 orders" }).click();
  await expect(page.getByRole("button", { name: "FRONTEND-CHECK", exact: true })).toBeVisible();
  await page.reload();
  await expect(page.getByRole("button", { name: "FRONTEND-CHECK", exact: true })).toBeVisible();
  await expect(page.getByRole("table").getByText("Awaiting analysis")).toBeVisible();
  await page.getByRole("button", { name: "FRONTEND-CHECK", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Original CSV row" })).toBeVisible();
  await expect(page.getByText("1234.56", { exact: true })).toBeVisible();
  await page.goto("/#/workspace/playbook");
  await page.getByLabel("In your own words").fill("Frontend integration test rule");
  await page.getByRole("button", { name: "Add to my playbook" }).click();
  await expect(page.getByRole("switch")).toBeChecked();
  await page.getByRole("switch").click();
  await expect(page.getByRole("switch")).not.toBeChecked();
  await page.reload();
  await expect(page.getByRole("switch")).not.toBeChecked();
  await page.getByRole("button", { name: "Delete rule: Frontend integration test rule" }).click();
  await expect(page.getByRole("switch")).toHaveCount(0);
  await page.goto("/#/workspace/account");
  await page.getByLabel("Name", { exact: true }).fill("Integration Verified");
  await page.getByRole("button", { name: "Save changes" }).click();
  await expect(page.locator(".profile strong")).toHaveText("Integration Verified");
});
